import { useState } from 'react'

const LANGUAGES = [
  { value: 'English', label: 'English' },
  { value: 'Telugu', label: 'తెలుగు' },
  { value: 'Hindi', label: 'हिन्दी' },
]

export default function ScholarshipAssistant() {
  const [language, setLanguage] = useState('English')
  const [question, setQuestion] = useState('')
  const [messages, setMessages] = useState([])
  const [loading, setLoading] = useState(false)
  const [error, setError] = useState('')

  async function submit(event) {
    event.preventDefault()
    const text = question.trim()
    if (!text || loading) return
    setMessages((current) => [...current, { role: 'user', text }])
    setQuestion('')
    setError('')
    setLoading(true)
    try {
      const response = await fetch('/api/chat', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ question: text, language }),
      })
      const data = await response.json()
      if (!response.ok) throw new Error(data.error || 'The assistant could not respond.')
      setMessages((current) => [...current, { role: 'assistant', text: data.answer, mode: data.mode }])
    } catch (requestError) {
      setError(requestError.message || 'Could not reach the assistant. Please try again.')
    } finally {
      setLoading(false)
    }
  }

  const isDemoMode = messages.some((message) => message.mode === 'demo')

  return (
    <section className="mx-auto max-w-3xl space-y-5">
      <div>
        <p className="text-sm font-semibold uppercase tracking-wide text-teal-800">Student Hub</p>
        <h1 className="mt-1 text-3xl font-bold text-slate-950">AI Scholarship Assistant</h1>
        <p className="mt-2 text-slate-600">Ask about scholarships in English, Telugu or Hindi. Answers use the Student Hub catalogue; verify important details with the official source.</p>
      </div>
      {isDemoMode && (
        <div role="status" className="rounded-lg border border-amber-300 bg-amber-50 p-4 text-sm text-amber-950">
          <strong className="block">Local demo mode</strong>
          This response uses the local scholarship catalogue. It was not generated by Gemini.
        </div>
      )}
      <div className="rounded-xl border border-slate-200 bg-white p-4 shadow-sm sm:p-6">
        <label htmlFor="assistant-language" className="mb-1 block text-sm font-semibold">Response language</label>
        <select id="assistant-language" value={language} onChange={(event) => setLanguage(event.target.value)} className="min-h-11 rounded-lg border border-slate-300 bg-white px-3 text-slate-900 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-teal-700">
          {LANGUAGES.map((item) => <option key={item.value} value={item.value}>{item.label}</option>)}
        </select>
        <div aria-live="polite" className="my-5 min-h-36 space-y-3">
          {messages.length === 0 && <p className="rounded-lg bg-slate-50 p-4 text-sm text-slate-600">Try: “What documents are listed for PM-USP CSSS?”</p>}
          {messages.map((message, index) => (
            <div key={`${index}-${message.role}`} className={`rounded-lg p-3 ${message.role === 'user' ? 'ml-6 bg-blue-50' : 'mr-6 bg-teal-50'}`}>
              <p className="mb-1 text-xs font-bold uppercase text-slate-600">{message.role === 'user' ? 'You' : message.mode === 'demo' ? 'Local Demo · Not AI-generated' : 'Assistant'}</p>
              <p className="whitespace-pre-wrap text-sm leading-6 text-slate-900">{message.text}</p>
            </div>
          ))}
          {loading && <p role="status" className="text-sm text-slate-600">Thinking…</p>}
        </div>
        {error && <p role="alert" className="mb-3 rounded-lg bg-red-50 p-3 text-sm text-red-800">{error}</p>}
        <form onSubmit={submit} className="flex flex-col gap-2 sm:flex-row">
          <label className="sr-only" htmlFor="assistant-question">Your question</label>
          <input id="assistant-question" value={question} onChange={(event) => setQuestion(event.target.value)} maxLength={1000} placeholder="Ask a scholarship question…" className="min-h-12 flex-1 rounded-lg border border-slate-300 px-3 text-slate-900 focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-teal-700" />
          <button type="submit" disabled={loading || !question.trim()} className="min-h-12 rounded-lg bg-brand-cobalt px-5 font-semibold text-white disabled:cursor-not-allowed disabled:opacity-50">{loading ? 'Sending…' : 'Send'}</button>
        </form>
      </div>
    </section>
  )
}
